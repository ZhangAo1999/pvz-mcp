"""Audited x86 bridge assembler for one exact 1.2.0.1073 build. No game asset input."""
import struct
CODE_VA=0x850000
DATA_VA=0x851000
hook=0x4211c0
stolen=bytes.fromhex('6aff6815e96e00')
code_va=CODE_VA
data_va=DATA_VA

def assemble():
    M=dict(heartbeat=12,board=16,epoch=20,busy=24,paused=28,remaining=32,speed=36,
           completed=40,request=44,ack=48,command=52,result=56,arg0=60,arg1=64,
           arg2=68,expected_epoch=72,reply=76,scene=80,stop=84,admin_events=88,auto_pause_play=92,
           advanced=96,total_updates=100,last_tick=104,app=112,app_busy=116,
           level_override=120,app_heartbeat=124)
    code=bytearray(); labels={}; fix=[]
    def e(h): code.extend(bytes.fromhex(h))
    def u(n): code.extend(struct.pack('<I',n&0xffffffff))
    def mark(s):
        assert s not in labels; labels[s]=len(code)
    def j(op,label): e(op); fix.append((len(code),label)); u(0)
    def call(va): e('e8'); fix.append((len(code),va));u(0)
    def movm(k,v): e('c747');e('%02x'%M[k]);u(v)
    def cmpm(k,v):e('817f');e('%02x'%M[k]);u(v)
    def seterr(n): movm('result',n); j('e9','ack')
    def native(va): call(va)

    mark('entry');e('9c60') # pushfd,pushad
    e('8bf1 bf');u(data_va) # esi=Board, edi=mailbox
    movm('busy',1);e('ff470c') # heartbeat
    e('397710');j('0f84','same_board')
    e('837f1000');j('0f84','first_board')
    movm('paused',1)
    mark('first_board');e('897710 ff4714');movm('remaining',0);movm('stop',4)
    mark('same_board');e('8b86a4000000 894770 8b8020090000 894750')
    cmpm('auto_pause_play',1);j('0f85','auto_pause_done');cmpm('scene',3);j('0f85','auto_pause_done')
    movm('paused',1);movm('auto_pause_play',0)
    mark('auto_pause_done')
    e('8b472c 3b4730');j('0f84','simulate')
    e('837f340a');j('0f83','simulate') # app/lifecycle commands belong to the outer hook
    movm('result',0);movm('reply',0)
    e('837f4800');j('0f84','epoch_ok')
    e('8b4748 3b4714');j('0f84','epoch_ok');seterr(2)
    mark('epoch_ok')
    e('8b4734 83f801');j('0f84','pause')
    e('83f802');j('0f84','resume')
    e('83f803');j('0f84','advance')
    e('83f804');j('0f84','placement')
    e('83f805');j('0f84','placement')
    e('83f806');j('0f84','sun')
    seterr(1)
    mark('pause');movm('paused',1);movm('remaining',0);movm('stop',5);j('e9','ack')
    mark('resume');movm('paused',0);movm('remaining',0);j('e9','speed')
    mark('advance')
    e('8b473c 85c0');j('0f8e','bad_arg');e('3d204e0000');j('0f87','bad_arg')
    e('894720');movm('advanced',0);movm('paused',1)
    mark('speed');e('8b4740 83f801');j('0f82','bad_arg');e('83f820');j('0f87','bad_arg')
    e('894724');movm('stop',0);j('e9','ack')
    mark('sun');cmpm('paused',1);j('0f85','not_paused');cmpm('scene',3);j('0f85','not_playing')
    e('8b473c 3d06270000');j('0f87','bad_arg') # <=9990
    e('898678550000 ff4758');j('e9','ack')

    mark('placement')
    cmpm('paused',1);j('0f85','not_paused');cmpm('scene',3);j('0f85','not_playing')
    # Adventure and Zombotany share the audited normal seed/fee/grid input path.
    e('8b86a4000000 83b81c09000000');j('0f84','placement_mode_ok')
    e('83b81c09000010');j('0f85','unsupported_mode')
    mark('placement_mode_ok')
    e('8b8650010000 83783000');j('0f85','cursor_busy')
    e('8b86 5c010000 85c0');j('0f84','bad_arg')
    e('8b4f3c 85c9');j('0f88','bad_arg');e('3b4824');j('0f83','bad_arg')
    e('83f90a');j('0f83','bad_arg')
    e('6bc950 8d6c0828') # ebp=card
    e('8b4740 83f805');j('0f87','bad_arg')
    e('8b4f44 83f908');j('0f87','bad_arg')
    # Check grid legality with original function: EAX=row, stack Board,col,type.
    e('8b4534 83f830');j('0f85','effective_type');e('8b4538')
    mark('effective_type');e('50 ff7744 56 8b4740');native(0x419d00)
    e('89474c 85c0');j('0f85','illegal_grid')
    e('60 8bf5');native(0x49e0a0);e('0fb6c0 a3');u(data_va+M['reply']);e('61')
    cmpm('reply',0);j('0f84','card_unavailable')
    cmpm('command',4);j('0f84','ack')
    # Exact native selection + coordinate conversion, audited in controller-abi.
    e('55');native(0x49e130)
    e('8b8650010000 83783001');j('0f85','selection_failed')
    e('8b4f3c 394824');j('0f85','selection_failed')
    e('60 8bde 8b4740 8b4f44');native(0x428350)
    e('83c028 a3');u(data_va+M['reply']);e('61')
    e('ff774c 8b4744 6bc050 83c050 50 56 33c9');native(0x41bc10)
    movm('reply',1);j('e9','ack')
    mark('selection_failed');e('60 8bce');native(0x4189e0);e('61');seterr(10)
    mark('cursor_busy');seterr(9)
    mark('illegal_grid');seterr(6)
    mark('card_unavailable');seterr(7)
    mark('not_paused');seterr(3)
    mark('not_playing');seterr(4)
    mark('unsupported_mode');seterr(8)
    mark('bad_arg');seterr(5)
    mark('ack');e('8b472c 894730')

    mark('simulate');e('8b5f24') # batch limit
    cmpm('paused',0);j('0f84','run_batch')
    cmpm('remaining',0);j('0f84','exit')
    mark('run_batch')
    e('8b86a4000000 39b068080000');j('0f85','board_gone')
    e('8b8020090000 894750')
    cmpm('paused',0);j('0f84','do_update')
    cmpm('scene',3);j('0f85','scene_stop')
    e('80be7c01000000');j('0f85','native_paused')
    mark('do_update')
    e('8bae a4000000') # retain App independently: update may destroy the Board
    e('8b5714') # also retain generation: the allocator may reuse the same address
    e('60 8bce');j('e8','trampoline');e('61')
    e('ff4764 ff4728')
    e('395714');j('0f85','board_gone')
    e('39b568080000');j('0f85','board_gone')
    e('8b8684550000 894768')
    cmpm('paused',0);j('0f84','batch_next')
    e('ff4f20 ff4760');cmpm('remaining',0);j('0f84','budget_done')
    mark('batch_next');e('4b');j('0f85','run_batch');j('e9','exit')
    mark('budget_done');movm('stop',1);j('e9','exit')
    mark('scene_stop');movm('stop',2);j('e9','stop_budget')
    mark('native_paused');movm('stop',3);j('e9','stop_budget')
    mark('board_gone');movm('stop',4)
    cmpm('paused',0);j('0f85','stop_budget')
    movm('remaining',0);j('e9','exit')
    mark('stop_budget');movm('remaining',0);movm('paused',1)
    mark('exit');movm('busy',0);e('619dc3')
    mark('trampoline');code.extend(stolen);j('e9',hook+len(stolen))
    mark('constructor')
    e('9c60 b8');u(data_va)
    e('ff4014 c7401000000000 c7402000000000 c7406800000000 c7405800000000 894870 619d')
    ctor=0x413930;ctor_stolen=bytes.fromhex('6aff682ad56e00')
    code.extend(ctor_stolen);j('e9',ctor+7)
    mark('level_override')
    e('9c 833d');u(data_va+M['level_override']);e('00');j('0f84','level_store')
    e('a1');u(data_va+M['level_override'])
    mark('level_store');e('9d 898568550000');j('e9',0x416d46)
    level_hook=0x416d40;level_stolen=bytes.fromhex('898568550000')

    # The App hook runs without a Board (title/menu included). Lifecycle work must
    # execute here, before Board::Update is on the stack, so replacing a Board can
    # never invalidate a caller still using that Board.
    app_hook=0x45f8c0;app_stolen=bytes.fromhex('558bec83e4f8')
    mark('app_entry');e('9c60 8bf1 bf');u(data_va)
    movm('app_busy',1);e('897770 ff477c 8b8620090000 894750')
    e('8b472c 3b4730');j('0f84','app_update')
    e('837f340a');j('0f82','app_update')
    movm('result',0);movm('reply',0)
    e('80be6a05000000');j('0f84','app_loading')
    e('837f4800');j('0f84','app_epoch_ok');e('8b4748 3b4714');j('0f84','app_epoch_ok')
    movm('result',2);j('e9','app_ack')
    mark('app_epoch_ok')
    cmpm('command',10);j('0f84','menu')
    cmpm('command',11);j('0f84','start_game')
    cmpm('command',12);j('0f84','select_seeds')
    cmpm('command',13);j('0f84','query_seeds')
    movm('result',1);j('e9','app_ack')
    mark('menu')
    e('8b8e6c080000 85c9');j('0f84','menu_without_title')
    e('80b9b900000000');j('0f84','app_loading')
    e('60 6a0d');native(0x4a4480);e('61');j('e9','menu_reset')
    mark('menu_without_title')
    for pointer,method in [(0x878,0x45c6a0),(0x87c,0x45c800),(0x880,0x45c910)]:
        e('83be');u(pointer);e('00');j('0f84','menu_skip_'+hex(pointer))
        e('60');native(method);e('61');mark('menu_skip_'+hex(pointer))
    e('60 8bce');native(0x45c4a0);e('61')
    mark('menu_reset');movm('board',0);e('ff4714');movm('paused',0);movm('remaining',0);movm('speed',1);movm('auto_pause_play',0)
    j('e9','app_ack')
    mark('start_game')
    e('83be6c08000000');j('0f85','app_menu_required')
    e('83be5009000000');j('0f84','app_no_profile')
    e('8b473c 83f846');j('0f87','app_bad_arg')
    e('83f82b');j('0f84','app_bad_arg');e('83f832');j('0f84','app_bad_arg')
    e('8b4740 83f832');j('0f87','app_bad_arg')
    for pointer,method in [(0x870,0x45c590),(0x878,0x45c6a0),(0x87c,0x45c800),(0x880,0x45c910)]:
        e('83be');u(pointer);e('00');j('0f84','start_skip_'+hex(pointer))
        e('60');native(method);e('61');mark('start_skip_'+hex(pointer))
    movm('paused',0);movm('remaining',0);movm('speed',1);movm('auto_pause_play',1)
    e('8b473c 89861c090000 8b4740 894778')
    e('60 8bc6');native(0x45c450);e('61');movm('level_override',0)
    j('e9','app_ack')
    mark('query_seeds')
    e('83be5009000000');j('0f84','app_no_profile')
    e('33db')
    mark('query_seed_loop');j('e8','seed_available');e('8b474c 89049d');u(data_va+192)
    e('43 83fb30');j('0f82','query_seed_loop');j('e9','app_ack')

    mark('select_seeds')
    e('83be5009000000');j('0f84','app_no_profile')
    e('83be1c09000000');j('0f84','select_mode_ok')
    e('83be1c09000010');j('0f85','app_unsupported')
    mark('select_mode_ok')
    e('83be2009000002');j('0f85','app_no_chooser')
    e('8bae74080000 85ed');j('0f84','app_no_chooser')
    e('8b8668080000 39852c0d0000');j('0f85','app_no_chooser')
    e('807d6500');j('0f84','app_no_chooser')
    e('83bd500d000001');j('0f84','app_chooser_busy')
    e('83bd380d000000');j('0f85','app_chooser_busy')
    e('8b473c 83f801');j('0f82','app_bad_arg');e('83f80a');j('0f87','app_bad_arg')
    e('8b9668080000 8b925c010000 3b4224');j('0f85','app_wrong_deck')
    e('33db')
    mark('validate_seed_loop')
    e('60 8b9c9f80000000 83fb2f');j('0f87','invalid_seed_pop')
    j('e8','seed_available');cmpm('reply',0);j('0f84','invalid_seed_pop')
    e('6bcb3c 83bc0de000000003');j('0f84','seed_candidate_ok')
    e('83bc0de000000001');j('0f85','invalid_seed_pop')
    mark('seed_candidate_ok')
    e('83fb11');j('0f84','seed_trial_check');e('83fb12');j('0f85','seed_trial_ok')
    mark('seed_trial_check');e('8bc5 8bfb');native(0x49a320);e('84c0');j('0f85','invalid_seed_pop')
    mark('seed_trial_ok');e('61 43 3b5f3c');j('0f82','validate_seed_loop')
    # Refuse to disturb native fixed cards. Complete every native animation after
    # each removal, since removing one slot may move several later cards.
    e('33db')
    mark('check_fixed');e('6bc33c 8d8405bc000000 83782401');j('0f85','next_fixed')
    e('80783800');j('0f85','app_fixed_deck')
    mark('next_fixed');e('43 83fb31');j('0f82','check_fixed')
    e('33db')
    mark('remove_seeds');e('6bc33c 8d8405bc000000 83782401');j('0f85','next_remove')
    e('50 8bc5');native(0x49b990);j('e8','finish_seed_animations')
    mark('next_remove');e('43 83fb31');j('0f82','remove_seeds')
    e('33db')
    mark('add_seeds');e('8b849f80000000 6bc03c 8d8405bc000000 83782403');j('0f85','app_seed_unavailable')
    e('50 8bc5');native(0x49bb30);j('e8','finish_seed_animations')
    e('43 3b5f3c');j('0f82','add_seeds')
    e('8b473c 3b853c0d0000');j('0f85','app_wrong_deck')
    e('55');native(0x49c820)
    movm('paused',0);movm('remaining',0);movm('speed',1);movm('auto_pause_play',1)
    j('e9','app_ack')
    mark('invalid_seed_pop');e('61');j('e9','app_seed_unavailable')
    mark('app_no_chooser');movm('result',14);j('e9','app_ack')
    mark('app_chooser_busy');movm('result',15);j('e9','app_ack')
    mark('app_wrong_deck');movm('result',16);j('e9','app_ack')
    mark('app_fixed_deck');movm('result',17);j('e9','app_ack')
    mark('app_seed_unavailable');movm('result',18);j('e9','app_ack')
    mark('app_unsupported');movm('result',8);j('e9','app_ack')
    mark('app_loading');movm('result',11);j('e9','app_ack')
    mark('app_menu_required');movm('result',12);j('e9','app_ack')
    mark('app_no_profile');movm('result',13);j('e9','app_ack')
    mark('app_bad_arg');movm('result',5)
    mark('app_ack');e('8b472c 894730')
    mark('app_update');e('60 8bce');j('e8','app_trampoline');e('61')
    movm('app_busy',0);e('619dc3')
    mark('app_trampoline');code.extend(app_stolen);j('e9',app_hook+6)
    mark('seed_available');e('60 83fb28');j('0f85','seed_generic_available')
    e('8b8650090000 83b8e801000000 0f9fc0');j('e9','seed_available_result')
    mark('seed_generic_available');e('8bfb');native(0x460f00)
    mark('seed_available_result');e('0fb6c0 a3');u(data_va+M['reply']);e('61c3')
    mark('finish_seed_animations');e('60 33db')
    mark('finish_seed_loop');e('6bc33c 8d8405bc000000 8bcd');native(0x49ab30)
    e('43 83fb31');j('0f82','finish_seed_loop');e('61c3')
    for at,target in fix:
        va=code_va+labels[target] if isinstance(target,str) else target
        struct.pack_into('<i',code,at,va-(code_va+at+4))
    assert len(code)<4096
    data=bytearray(512);data[:4]=b'PZCT';struct.pack_into('<II',data,4,2,512)
    struct.pack_into('<I',data,M['speed'],1)
    hooks=[(hook,stolen,'entry'),(ctor,ctor_stolen,'constructor'),
        (level_hook,level_stolen,'level_override'),(app_hook,app_stolen,'app_entry')]
    return bytes(code),bytes(data),dict(labels={k:code_va+v for k,v in labels.items()},mailbox=M,
        version=2,code_va=code_va,data_va=data_va,code_bytes=len(code)),hooks
